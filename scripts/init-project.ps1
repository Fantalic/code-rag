# code-lightrag project initialization
# Run from project root to initialize a folder for LightRAG storage
# Usage: .\scripts\init-project.ps1 [project_path]
# Default project_path is current directory

param(
    [string]$ProjectPath = (Get-Location).Path
)

$CODERAG_DIR = Join-Path $ProjectPath ".coderag"
$RAG_STORAGE_DIR = Join-Path $CODERAG_DIR "rag_storage"
$ENV_FILE = Join-Path $ProjectPath ".env"

Write-Host "Initializing CodeLightRAG project at: $ProjectPath" -ForegroundColor Cyan
Write-Host ""

# Create .coderag directory
if (-not (Test-Path $CODERAG_DIR)) {
    New-Item -ItemType Directory -Path $CODERAG_DIR -Force | Out-Null
    Write-Host "[OK] Created .coderag folder" -ForegroundColor Green
} else {
    Write-Host "[SKIP] .coderag folder already exists" -ForegroundColor Yellow
}

# Create rag_storage subdirectory
if (-not (Test-Path $RAG_STORAGE_DIR)) {
    New-Item -ItemType Directory -Path $RAG_STORAGE_DIR -Force | Out-Null
    Write-Host "[OK] Created .coderag/rag_storage folder" -ForegroundColor Green
} else {
    Write-Host "[SKIP] .coderag/rag_storage already exists" -ForegroundColor Yellow
}

# Create or update .env file
$envContent = @"
# CodeLightRAG Project Configuration
# Generated by init-project.ps1

# LightRAG working directory (stores graph, vector DB, etc.)
LIGHTRAG_WORKING_DIR=.coderag/rag_storage
LIGHTRAG_URL=http://localhost:9621
LIGHTRAG_TIMEOUT=30
"@

if (Test-Path $ENV_FILE) {
    $existingContent = Get-Content $ENV_FILE -Raw -ErrorAction SilentlyContinue
    if ($existingContent -match "LIGHTRAG_WORKING_DIR") {
        Write-Host "[SKIP] .env already has LIGHTRAG_WORKING_DIR set" -ForegroundColor Yellow
    } else {
        $envContent | Set-Content $ENV_FILE -Force
        Write-Host "[OK] Updated .env with LIGHTRAG_WORKING_DIR" -ForegroundColor Green
    }
} else {
    $envContent | Set-Content $ENV_FILE -Force
    Write-Host "[OK] Created .env with LIGHTRAG_WORKING_DIR" -ForegroundColor Green
}

Write-Host ""
Write-Host "Project initialized successfully!" -ForegroundColor Green
Write-Host ""
Write-Host "Storage location: .coderag/rag_storage/"
Write-Host "Config file: .env"
Write-Host ""
Write-Host "To start the LightRAG server with this project:"
Write-Host "  1. Activate venv: .\venv\Scripts\Activate.ps1"
Write-Host "  2. Start server: lightrag-server --working-dir .\.coderag\rag_storage"
Write-Host ""
Write-Host "Or set environment variable and start server:"
Write-Host "  `$env:LIGHTRAG_WORKING_DIR = '.\.coderag\rag_storage'"
Write-Host "  lightrag-server"